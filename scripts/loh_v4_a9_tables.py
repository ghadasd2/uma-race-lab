def fmt(v, nd=2):
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return ""
    if isinstance(v, (bool,)) or str(v) in ("True", "False"):
        return "yes" if str(v) == "True" else "no"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v).replace("|", "/")


def table(df, cols=None, nd=2, names=None):
    cols = cols or list(df.columns)
    head = [names.get(c, c) if names else c for c in cols]
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(fmt(r[c], nd) for c in cols) + " |")
    return "\n".join(lines)


def ci(r, d="d_top3", lo="lo", hi="hi"):
    return f"{r[d]:+.2f} [{r[lo]:+.2f}, {r[hi]:+.2f}]"


def team_block(path):
    t = json.loads(Path(path).read_text())
    rows = []
    for b in t:
        rows.append({"uma": b["name"], "strategy": b["strategy"], **dict(zip(STAT, b["stats"])),
                     "cost": mock.stat_cost(b["stats"]), "skills": ", ".join(b["skills"])})
    return table(pd.DataFrame(rows))


